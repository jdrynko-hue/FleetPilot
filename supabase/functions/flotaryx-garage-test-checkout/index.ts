import Stripe from 'stripe';
import { createClient } from 'supabase';
import { createGarageSandboxCheckoutHandler } from './http_handler.ts';

// QA-only, default-off bootstrap. Production URL and Live Stripe keys are
// rejected before SDK construction. Deployment does not enable Checkout.
const qaUrl = 'https://fyestmquqvkdebxxbcky.supabase.co';
const url = Deno.env.get('SUPABASE_URL');
const stripeKey = Deno.env.get('STRIPE_SECRET_KEY') ?? '';
const anonKey = Deno.env.get('SUPABASE_ANON_KEY');
const serviceKey = Deno.env.get('SUPABASE_SERVICE_ROLE_KEY');
const enabled = Deno.env.get('FLOTARYX_GARAGE_SANDBOX_CHECKOUT') === 'true';

if (!enabled || url !== qaUrl || !/^(sk|rk)_test_[A-Za-z0-9]+$/.test(stripeKey) || !anonKey || !serviceKey || anonKey === serviceKey) {
  console.warn('garage_checkout_bootstrap_failure', !enabled ? 'disabled' :
    url !== qaUrl ? 'qa_url' : !/^(sk|rk)_test_[A-Za-z0-9]+$/.test(stripeKey) ? 'test_key_format' :
    !anonKey ? 'anon_key_missing' : !serviceKey ? 'service_key_missing' : 'keys_not_distinct');
  Deno.serve(() => new Response(JSON.stringify({ error: 'Garage Sandbox billing unavailable' }), {
    status: 503, headers: { 'Content-Type': 'application/json', 'Cache-Control': 'no-store',
      'Access-Control-Allow-Origin': 'https://flotaryx-qa-preview.fairdrake9.chatgpt.site', 'Vary': 'Origin' },
  }));
} else {
  const options = { auth: { persistSession: false, autoRefreshToken: false, detectSessionInUrl: false } };
  // Separate clients: a caller's bearer token never replaces service RPC Auth.
  const authClient = createClient(qaUrl, anonKey, options);
  const serviceClient = createClient(qaUrl, serviceKey, options);
  Deno.serve(createGarageSandboxCheckoutHandler({ enabled, paidRejoinEnabled: Deno.env.get('FLOTARYX_GARAGE_SANDBOX_PAID_REJOIN') === 'true', supabaseUrl: qaUrl, stripeKey }, {
    authClient, serviceClient,
    diagnostic(stage) { console.warn('garage_checkout_failure', stage); },
    createStripeClient(key) {
      const stripe = new Stripe(key, { httpClient: Stripe.createFetchHttpClient(),
        maxNetworkRetries: 1, timeout: 12000 });
      return {
        subscriptions: {retrieve: (id) => stripe.subscriptions.retrieve(id)},
        prices: { retrieve: (id) => stripe.prices.retrieve(id) },
        customers: { retrieve: (id) => stripe.customers.retrieve(id) },
        checkout: { sessions: {
          // Params are generated by the validated server coordinator, never
          // passed through from request JSON. Pinned SDK uses its default API.
          create: (params, requestOptions) => stripe.checkout.sessions.create(
            params as Stripe.Checkout.SessionCreateParams, requestOptions),
          retrieve: (id, params) => stripe.checkout.sessions.retrieve(id, params),
        } },
      };
    },
  }));
}
