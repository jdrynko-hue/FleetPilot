String authText(String en, String pl, {String? language}) {
  final code = language ?? AppLocale.language.value;
  if (code == 'pl') return pl;
  final index = authMessageKeys.indexOf(en);
  final row = authMessageTranslations[code];
  return row != null && index >= 0 ? row[index] : en;
}

