  static String get(String key, {String? language}) {
    final index = keys.indexOf(key);
    if (index < 0) return key;
    final code = language ?? AppLocale.language.value;
    final translated = labels[code];
    if (translated == null || translated.length != keys.length) {
      return labels['en']![index];
    }
    return translated[index];
  }

  static String format(String key, Map<String, Object> values,
      {String? language}) {
    var result = get(key, language: language);
    for (final entry in values.entries) {
      result = result.replaceAll('{'+entry.key+'}', entry.value.toString());
    }
    return result;
  }
